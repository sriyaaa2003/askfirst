"""Write results/results.md from results/summary.json and the sensitivity runs.

    python -m askfirst.report

No number is typed by hand: everything below is read from the run outputs.
"""
from __future__ import annotations

import json
from pathlib import Path

POLICY_LABEL = {
    "random": "random", "width": "widest interval first", "value": "highest value at stake first",
    "risk": "expected cost of acting alone", "evr": "expected value of review (askfirst)",
    "evr_ctx": "expected value of review, planner profile known", "oracle": "oracle (upper bound)",
}
SENS = {"results/sens_margin_half": "lost margin x0.5", "results/sens_margin_double": "lost margin x2",
        "results/sens_over_half": "overage cost x0.5", "results/sens_over_double": "overage cost x2"}


def pct(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def main(root: str = "results") -> None:
    root = Path(root)
    s = json.loads((root / "summary.json").read_text())
    d, h, b = s["data"], s["headline"], s["bootstrap_over_test_weeks"]
    L = []
    L.append("# askfirst results (generated by `python -m askfirst.report`)\n")
    L.append(f"Test: {d['test_weeks']} weeks, {d['test_decisions']:,} ordering decisions "
             f"({d['zero_demand_share_test'] * 100:.1f}% had zero demand). Train {d['train_decisions']:,}, "
             f"calibration {d['calibration_decisions']:,} decisions.\n")
    L.append("## Forecast accuracy (WAPE on test weeks, lower is better)\n")
    L.append("| forecast | WAPE |\n|---|---|")
    for k, v in s["wape_test"].items():
        L.append(f"| {k} | {v:.3f} |")
    L.append("\n## Calibration\n")
    c = s["interval_80_coverage"]
    L.append(f"80% interval coverage on test: {pct(c['overall'])} overall; "
             f"{pct(c['top10pct_evr'])} on the 10% of decisions with the highest value of review; "
             f"{pct(c['rest'])} on the rest.\n")
    L.append("| department | 80% coverage | order-up-to target | achieved |\n|---|---|---|---|")
    for k, v in c["by_dept"].items():
        sv = s["order_up_to_service_level"][k]
        L.append(f"| {k} | {pct(v)} | {pct(sv['target'])} | {pct(sv['achieved'])} |")
    L.append("\n## Autonomy frontier (planner removes 50% of the model error; router assumes the same)\n")
    p = h["0.5"]
    L.append(f"Reviewing every decision would cut the shortage and surplus cost by {p['savings_all_human_pct']:.1f}% "
             f"(before paying for the reviews).\n")
    L.append("| ranking rule | share of that saving captured at a 5% / 10% / 20% review budget "
             "| review share needed for 50% / 80% of it |\n|---|---|---|")
    for k, lab in POLICY_LABEL.items():
        L.append(f"| {lab} | {pct(p[k + '_capture_at_5pct'])} / {pct(p[k + '_capture_at_10pct'])} / "
                 f"{pct(p[k + '_capture_at_20pct'])} | {pct(p[k + '_fraction_for_50pct'], 0)} / "
                 f"{pct(p[k + '_fraction_for_80pct'], 0)} |")
    L.append("\n95% confidence intervals from resampling the test weeks (10% budget): " + "; ".join(
        f"{POLICY_LABEL[k]} {pct(v['capture_10pct'])} [{pct(v['ci95'][0])}, {pct(v['ci95'][1])}]"
        for k, v in b.items() if k in POLICY_LABEL) + ". "
        f"Expected value of review minus highest value at stake: "
        f"{100 * b['evr_minus_value_capture_10pct']['diff']:.1f} points "
        f"[{100 * b['evr_minus_value_capture_10pct']['ci95'][0]:.1f}, "
        f"{100 * b['evr_minus_value_capture_10pct']['ci95'][1]:.1f}].\n")
    L.append(f"Spearman correlation of the value-of-review score with the expected cost of acting alone: "
             f"{s['spearman_evr_vs_risk']:.4f} (uniform planner), {s['spearman_evr_ctx_vs_risk']:.3f} "
             f"(planner who helps most where a price drop or event is visible).\n")
    L.append("### When the planner is better or worse than the router assumes\n")
    L.append("| planner | all-human saving | askfirst capture at 10% | oracle capture at 10% |\n|---|---|---|---|")
    for k, v in h.items():
        L.append(f"| {k} | {v['savings_all_human_pct']:.1f}% | {pct(v['evr_capture_at_10pct'])} | "
                 f"{pct(v['oracle_capture_at_10pct'])} |")
    L.append("\n## What a review budget costs\n")
    L.append("| reviews | per week | planner hours per week |\n|---|---|---|")
    for k, v in s["workload"].items():
        L.append(f"| {k} of decisions | {v['reviews_per_week']:,.0f} | {v['planner_hours_per_week']:.0f} |")
    L.append("\n### Net saving after paying for reviews, by price of one review\n")
    L.append("| cost per review | best share to review | net saving vs all-automatic |\n|---|---|---|")
    for k, v in s["review_cost_sweep"].items():
        L.append(f"| {v['review_cost']:.2f} | {pct(v['best_fraction'], 0)} | {v['net_saving_vs_all_auto_pct']:.1f}% |")
    L.append("\n## Sensitivity to the cost assumptions\n")
    L.append("| variant | askfirst capture at 10% | highest value at stake | widest interval | "
             "best share to review at base review cost |\n|---|---|---|---|---|")
    rows = [("base", root)] + [(lab, Path(path)) for path, lab in SENS.items()]
    for lab, path in rows:
        f = path / "summary.json"
        if not f.exists():
            continue
        t = json.loads(f.read_text())
        q = t["headline"]["0.5"]
        L.append(f"| {lab} | {pct(q['evr_capture_at_10pct'])} | {pct(q['value_capture_at_10pct'])} | "
                 f"{pct(q['width_capture_at_10pct'])} | {pct(t['review_cost_sweep']['1']['best_fraction'], 0)} |")
    (root / "results.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {root / 'results.md'}")


if __name__ == "__main__":
    main()
